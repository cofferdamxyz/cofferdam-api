/**
 * Compiles the workspace's product skills (workspace decision 0048) into
 * `src/services/chat/facts.generated.ts`, the facts block the chat's system
 * prompt carries. Only user-audience skills compile; a `[built]` bullet
 * becomes a fact, a `[planned]` bullet a "Not yet:" line, anything else is
 * ignored. The workspace is `..` on the Mac (this repository sits inside it)
 * and `../cofferdam` in a cloud session; `--check` compiles to memory and
 * exits 1 when the committed file differs (test/facts.test.ts runs it).
 *
 *   node scripts/compile-skills.mjs            # writes the file
 *   node scripts/compile-skills.mjs --check    # compares only
 */

import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');
const OUT = join(repo, 'src', 'services', 'chat', 'facts.generated.ts');

/** The workspace's `skills/` directory, or null outside a workspace. */
export function skillsDir() {
  for (const candidate of [resolve(repo, '..', 'skills'), resolve(repo, '..', 'cofferdam', 'skills')]) {
    if (existsSync(candidate)) return candidate;
  }
  return null;
}

function frontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const meta = {};
  if (!m) return { meta, body: text };
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: text.slice(m[0].length) };
}

/** The compiled facts of every user-audience skill, in file order. */
export function compile(dir) {
  const skills = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, 'SKILL.md')))
    .map((d) => d.name)
    .sort();
  const lines = [];
  const sources = [];
  for (const name of skills) {
    const path = join(dir, name, 'SKILL.md');
    const text = readFileSync(path, 'utf8');
    const { meta, body } = frontmatter(text);
    if (meta.audience !== 'user') continue;
    sources.push({ name, hash: createHash('sha256').update(text).digest('hex').slice(0, 16) });
    for (const raw of body.split('\n')) {
      const m = /^- \[(built|planned)\] (.+)$/.exec(raw.trim());
      if (!m) continue;
      lines.push(m[1] === 'built' ? `- ${m[2]}` : `- Not yet: ${m[2]}`);
    }
  }
  const block = ['Facts about Cofferdam. Rely on them; for anything marked "Not yet", say it is coming and never describe it as working.', ...lines].join('\n');
  return { block, sources };
}

export function render({ block, sources }) {
  const src = sources.map((s) => `${s.name}@${s.hash}`).join(', ');
  return [
    '// Generated by scripts/compile-skills.mjs from the workspace skills (decision 0048). Do not edit.',
    `// Sources: ${src}`,
    '',
    '/** The product facts the chat carries in its system prompt: user-audience skills, built and planned. */',
    `export const PRODUCT_FACTS = ${JSON.stringify(block)};`,
    '',
    `export const PRODUCT_FACTS_SOURCES = ${JSON.stringify(sources)} as const;`,
    '',
  ].join('\n');
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const dir = skillsDir();
  if (!dir) {
    console.error('compile-skills: no workspace skills/ directory beside this repository');
    process.exit(2);
  }
  const out = render(compile(dir));
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== out) {
      console.error(`compile-skills: ${OUT} is stale; run node scripts/compile-skills.mjs`);
      process.exit(1);
    }
    console.log('compile-skills: up to date');
  } else {
    writeFileSync(OUT, out);
    console.log(`compile-skills: wrote ${OUT} (${out.length} chars)`);
  }
}
